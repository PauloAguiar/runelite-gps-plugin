#!/usr/bin/env python3
"""Generate the portal nexus rows of teleportation_portals_poh.tsv from the portal chamber rows.

The portal nexus keeps its unlocked teleports in 45 slot varbits (POH_NEXUS_TELE_1..45), each
holding a teleport's key from the nexus enum (game cache enum 1377, client script 2671, read
2026-10-13), and its left-click teleport in POH_NEXUS_LEFT_CLICK (6653). For every chamber
portal destination this writes two rows with the same landing:
  menu row        "Teleport Portal Nexus 33408", any slot holding the key, 3 ticks (open the
                  Teleport Menu, press the key)
  left-click row  the left-click varbit holding the key, 1 tick
Varrock, Camelot and Watchtower slots also offer their Grand Exchange, Seers' Village and
Yanille alternates, so those rows are gated on the primary's slot (and the alternate's own key
for the left-click). The chamber's own toggle varbits (4560, 4585, 4548) are dropped; the
respawn and Troll Stronghold state gates are kept. The block between the markers is regenerated
on every run; the chamber rows are the source of truth, so edit those and rerun:
  python scripts/derive_nexus_rows.py
"""
import io
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
PATH = os.path.join(ROOT, 'src', 'main', 'resources', 'transports', 'teleportation_portals_poh.tsv')
BEGIN = '# >>> Portal nexus rows: generated by scripts/derive_nexus_rows.py from the portal chamber rows above, do not edit'
END = '# <<< Portal nexus rows'
ORIGIN = '1928 5731 0'
ACTION = 'Teleport Portal Nexus 33408'
LEFT_CLICK = 6653
SLOTS = list(range(6654, 6669)) + [6554, 6555, 6556] + list(range(10080, 10092)) + list(range(10019, 10024)) + list(range(20111, 20121))
TOGGLES = {'4560', '4585', '4548'}
MENU_TICKS = '3'
LEFT_CLICK_TICKS = '1'
# Chamber display info -> (slot key, left-click key); alternates ride on the primary's slot.
KEYS = {
    'Varrock Portal': (1, 1), 'Grand Exchange Portal': (1, 151), 'Lumbridge Portal': (2, 2), 'Falador Portal': (3, 3),
    'Camelot Portal': (4, 4), "Seers' Village Portal": (4, 154), 'Ardougne Portal': (5, 5),
    'Watchtower Portal': (6, 6), 'Yanille Portal': (6, 156), 'Senntisten Portal': (7, 7), 'Marim Portal': (8, 8),
    'Kharyrll Portal': (9, 9), 'Lunar Isle Portal': (10, 10), 'Kourend Portal': (11, 11),
    'Waterbirth Island Portal': (12, 12), 'Fishing Guild Portal': (13, 13), 'Annakarl Portal': (14, 14),
    'Troll Stronghold Portal': (15, 15), 'Catherby Portal': (16, 16), 'Ghorrock Portal': (17, 17),
    'Carrallanger Portal': (18, 18), 'Weiss Portal': (19, 19), 'Arceuus Library Portal': (20, 20),
    'Draynor Manor Portal': (21, 21), 'Battlefront Portal': (22, 22), 'Mind Altar Portal': (23, 23),
    'Salve Graveyard Portal': (24, 24), "Fenkenstrain's Castle Portal": (25, 25), 'West Ardougne Portal': (26, 26),
    'Harmony Island Portal': (27, 27), 'Cemetery Portal': (28, 28), 'Barrows Portal': (29, 29),
    'Ape Atoll Dungeon Portal': (30, 30), 'Civitas illa Fortis Portal': (31, 31), 'Trollheim Portal': (32, 32),
    'Paddewwa Portal': (33, 33), 'Lassar Portal': (34, 34), 'Dareeyak Portal': (35, 35), 'Ourania Portal': (36, 36),
    'Barbarian Outpost Portal': (37, 37), 'Port Khazard Portal': (38, 38), 'Ice Plateau Portal': (39, 39),
    'Respawn Portal': (40, 40),
}


def nexus_name(display):
    """"Varrock Portal" -> "Portal Nexus: Varrock"; "Respawn Portal (Lumbridge)" -> "Portal Nexus: Respawn (Lumbridge)"."""
    return 'Portal Nexus: ' + display.replace(' Portal', '', 1)


def keys_for(display):
    base = display.split(' (')[0]
    return KEYS.get(base)


def main():
    raw = io.open(PATH, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in raw else '\n'
    lines = raw.split(nl)
    if BEGIN in lines:
        start = lines.index(BEGIN)
        stop = lines.index(END)
        base = lines[:start] + lines[stop + 1:]
    else:
        base = lines
    while base and base[-1] == '':
        base.pop()
    header = next(l for l in base if l.startswith('# Origin'))
    columns = header.lstrip('# ').split('\t')
    col = {name: i for i, name in enumerate(columns)}
    seen = set()
    rows = []
    for line in base:
        if line.startswith('#') or not line.strip():
            continue
        fields = line.split('\t')
        fields += [''] * (len(columns) - len(fields))
        display = fields[col['Display info']]
        keys = keys_for(display)
        if keys is None or 'Portal Nexus' in fields[col['menuOption menuTarget objectID']]:
            if keys is None and 'Portal Nexus' not in fields[col['menuOption menuTarget objectID']]:
                print('no nexus key for', display, file=sys.stderr)
            continue
        gates = [g for g in fields[col['Varbits']].split(';') if g and g.split('=')[0].split('>')[0].split('<')[0] not in TOGGLES]
        key = (display, fields[col['Destination']], tuple(gates), fields[col['Quests']])
        if key in seen:
            continue
        seen.add(key)
        slot_key, click_key = keys
        menu_gate = '||'.join('%d=%d' % (slot, slot_key) for slot in SLOTS)
        for gate, ticks in ((menu_gate, MENU_TICKS), ('%d=%d' % (LEFT_CLICK, click_key), LEFT_CLICK_TICKS)):
            out = [''] * len(columns)
            out[col['Origin']] = ORIGIN
            out[col['Destination']] = fields[col['Destination']]
            out[col['menuOption menuTarget objectID']] = ACTION
            out[col['Varbits']] = ';'.join(gates + [gate])
            out[col['Duration']] = ticks
            out[col['Display info']] = nexus_name(display)
            out[col['Quests']] = fields[col['Quests']]
            rows.append('\t'.join(out).rstrip('\t'))
    text = nl.join(base + ['', BEGIN] + rows + [END]) + nl
    io.open(PATH, 'w', encoding='utf-8', newline='').write(text)
    print('nexus rows:', len(rows), 'from', len(seen), 'destinations')


if __name__ == '__main__':
    main()
